"""全局常量（约定：模块级全大写命名，供各模块 import 复用）。

按需往里加，避免在业务代码里散落硬编码。

分组建议：
    - 意图常量：INTENT_XXX
    - 分页/限流：MAX_PAGE_SIZE 等
    - 会话：上下文条数等
"""

# 查询历史消息（GET /assistant/chat/messages）的默认条数。
# 注意：这是「给人看」的分页默认值，不影响模型上下文，也不影响存储。
CHAT_HISTORY_LIMIT = 20

# 上下文压缩（SummarizationMiddleware）：
# 消息累计到 TRIGGER 条时，把早期对话压缩成一段摘要，保留最近 KEEP 条原文。
# 为什么是摘要而不是截断：截断会直接丢掉「用户想找什么、已经查到什么」，
# 模型下一轮就断片；摘要有损但保语义。
CHAT_SUMMARY_TRIGGER = 40
CHAT_SUMMARY_KEEP = 20

# 工具调用轮数上限（一轮 = 模型要工具 → 执行 → 模型再想）。
# 防止模型反复要工具陷入死循环；到上限后不再给它工具，逼它直接回答。
MAX_TOOL_ROUNDS = 3

# 单轮 token 上限（含工具轮 + 识图）。
# 日配额只管"总量"，管不住"一轮烧穿"：5 张图 + 长文档 + 3 轮工具完全可能
# 单轮就冲到几万 token。超过这个数就不再给工具，让它用已有信息收尾。
MAX_TURN_TOKENS = 30_000

# 单轮最多读几张图（每张 = 一次视觉模型调用，多了又慢又贵）。
# 与前端 ATTACHMENT_RULES.maxCount 对齐：前端允许传 5 个附件，这里也得能读 5 张，
# 不然第 4、5 张会被静默丢掉，用户完全不知道。
MAX_IMAGES = 5

# ---------- 文档解析与切块 ----------
# 一份 50 页讲义约 3 万字，整篇塞进 prompt 是 3 万 token——日配额 10 万，三轮就爆。
# 所以切块后只带最相关的几块进去。
DOC_CHUNK_SIZE = 400      # 每块目标字数
DOC_CHUNK_OVERLAP = 80    # 相邻块重叠，避免答案正好被切断
# 每轮带几块进 prompt：4 块 ≈ 1600 字 ≈ 1000 token
DOC_TOP_K = 4

# ---------- 解析路由（按「每页文字量」分流，不看图片清不清晰）----------
# 判据来自实测：PDF 的文本层是作者给的，比 OCR 准得多，能直抽就不要花 60 秒走 MinerU。
# 一份 1 页的成绩单：直抽 0.01 秒 / 2454 字；MinerU 60 秒 / 20149 字（86% 是 HTML 标签）。
PAGE_TEXT_RICH = 200      # > 200 字/页：富文本页，直接抽
PAGE_TEXT_LOW = 50        # ≤ 50 字/页：视作扫描页 / 纯图片页
# 一份文档里低密度页超过 10 张时，只对前 10 张做视觉补全（成本闸门）
MAX_IMAGE_PAGES = 10

# 表格页识别：一页里「含 ≥2 个数字的行」超过这个比例，就当表格页。
# 为什么需要它：教务系统导出的成绩单，PDF 里 "期" 字被画在错误的 x 坐标上，
# 直抽得到的是「春季学创期新创业基础」——乱序是**文件本身**的问题，
# pypdfium2 和 pdfplumber 抽出来一模一样，按坐标重排也修不好（坐标就是错的）。
# 只有版面级解析（MinerU）能还原，所以这类页必须走 OCR 那条路。
# 实测：这份成绩单 89% 的行含 ≥2 个数字；普通讲义正文远低于 10%。
TABLE_NUMERIC_RATIO = 0.4
# 表格页占比超过这个值 → 整份文档交给 MinerU
TABLE_PAGE_RATIO = 0.5
